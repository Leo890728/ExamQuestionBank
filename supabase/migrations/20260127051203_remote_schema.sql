CREATE OR REPLACE FUNCTION public.add_question(content text, explanation text DEFAULT NULL::text, question_type text DEFAULT NULL::text, difficulty text DEFAULT NULL::text, subject text DEFAULT NULL::text, category text DEFAULT NULL::text, year smallint DEFAULT NULL::smallint, source text DEFAULT NULL::text, options jsonb DEFAULT '[]'::jsonb, tag_ids bigint[] DEFAULT NULL::bigint[], creator uuid DEFAULT NULL::uuid, status text DEFAULT NULL::text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
    v_question_id BIGINT;
    v_type public.question_type;
    v_difficulty public.question_difficulty;
    v_creator UUID;
    v_options JSONB;
    v_has_options BOOLEAN;
BEGIN
    IF content IS NULL OR btrim(content) = '' THEN
        RAISE EXCEPTION 'content is required';
    END IF;

    v_options := COALESCE(options, '[]'::jsonb);
    v_has_options := CASE
        WHEN jsonb_typeof(v_options) = 'array' THEN jsonb_array_length(v_options) > 0
        ELSE false
    END;

    IF question_type IN ('essay', 'multipleChoice') THEN
        v_type := question_type::public.question_type;
    ELSE
        v_type := CASE WHEN v_has_options THEN 'multipleChoice' ELSE 'essay' END;
    END IF;

    IF difficulty = 'medium' THEN
        v_difficulty := 'normal';
    ELSIF difficulty IN ('easy', 'normal', 'hard', 'insane') THEN
        v_difficulty := difficulty::public.question_difficulty;
    ELSE
        v_difficulty := 'normal';
    END IF;

    v_creator := auth.uid();
    IF v_creator IS NULL THEN
        v_creator := creator;
    END IF;

    INSERT INTO public.question (
        content,
        explanation,
        type,
        difficulty,
        subject,
        category,
        year,
        source,
        creator
    )
    VALUES (
        btrim(content),
        NULLIF(btrim(explanation), ''),
        v_type,
        v_difficulty,
        NULLIF(btrim(subject), ''),
        NULLIF(btrim(category), ''),
        year,
        NULLIF(btrim(source), ''),
        v_creator
    )
    RETURNING id INTO v_question_id;

    IF v_has_options THEN
        INSERT INTO public.question_option (question_id, content, is_correct, "order")
        SELECT
            v_question_id,
            btrim(COALESCE(opt->>'content', '')),
            COALESCE((opt->>'is_correct')::boolean, false),
            COALESCE((opt->>'order')::smallint, ord::smallint)
        FROM jsonb_array_elements(v_options) WITH ORDINALITY AS t(opt, ord)
        WHERE btrim(COALESCE(opt->>'content', '')) <> '';
    END IF;

    IF tag_ids IS NOT NULL AND array_length(tag_ids, 1) > 0 THEN
        INSERT INTO public.question_tag (question_id, tag_id)
        SELECT v_question_id, unnest(tag_ids)
        ON CONFLICT DO NOTHING;
    END IF;

    RETURN v_question_id;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.get_bookmarks()
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE result JSON; current_user_id UUID;
BEGIN
  current_user_id := auth.uid();
  SELECT COALESCE(json_agg(json_build_object('id', b.question_id, 'bookmarked_at', b.created_at, 'content', q.content, 'type', q.type, 'difficulty', q.difficulty, 'subject', q.subject) ORDER BY b.created_at DESC), '[]'::json) INTO result FROM bookmark b JOIN question q ON q.id = b.question_id WHERE b.user_id = current_user_id;
  RETURN result;
END;
$function$
