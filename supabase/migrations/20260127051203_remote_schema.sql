CREATE OR REPLACE FUNCTION public.review_flashcard(p_flashcard_id bigint, p_rating integer)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE current_user_id UUID; fc RECORD; new_ease DECIMAL; new_interval INTEGER; new_rep INTEGER; new_status TEXT; result JSON;
BEGIN
  current_user_id := auth.uid();
  SELECT * INTO fc FROM flashcard WHERE id = p_flashcard_id AND user_id = current_user_id;
  IF fc IS NULL THEN RAISE EXCEPTION 'Flashcard not found'; END IF;
  IF p_rating < 2 THEN new_rep := 0; new_interval := 1; new_ease := fc.ease_factor;
  ELSE new_rep := fc.repetition + 1;
    IF new_rep = 1 THEN new_interval := 1; ELSIF new_rep = 2 THEN new_interval := 6; ELSE new_interval := ROUND(fc.interval_days * fc.ease_factor); END IF;
    new_ease := GREATEST(1.3, fc.ease_factor + (0.1 - (3 - p_rating) * (0.08 + (3 - p_rating) * 0.02)));
  END IF;
  IF new_rep >= 3 AND new_interval >= 21 THEN new_status := 'mastered'; ELSIF new_rep >= 1 THEN new_status := 'review'; ELSE new_status := 'learning'; END IF;
  UPDATE flashcard SET ease_factor = new_ease, interval_days = new_interval, repetition = new_rep, status = new_status, next_review_date = CURRENT_DATE + new_interval, last_reviewed_at = NOW(), review_count = review_count + 1 WHERE id = p_flashcard_id;
  SELECT json_build_object('id', p_flashcard_id, 'ease_factor', new_ease, 'interval_days', new_interval, 'status', new_status, 'next_review_date', CURRENT_DATE + new_interval) INTO result;
  RETURN result;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.save_exam_result(p_exam_id bigint DEFAULT NULL::bigint, p_exam_name text DEFAULT ''::text, p_score numeric DEFAULT 0, p_correct_count integer DEFAULT 0, p_total_count integer DEFAULT 0, p_duration_seconds integer DEFAULT NULL::integer, p_answers_json jsonb DEFAULT NULL::jsonb, p_wrong_question_ids bigint[] DEFAULT NULL::bigint[])
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE result_id BIGINT; current_user_id UUID; wq_id BIGINT; result JSON;
BEGIN
  current_user_id := auth.uid();
  IF current_user_id IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  INSERT INTO exam_result (user_id, exam_id, exam_name, score, correct_count, total_count, duration_seconds, answers_json) VALUES (current_user_id, p_exam_id, p_exam_name, p_score, p_correct_count, p_total_count, p_duration_seconds, p_answers_json) RETURNING id INTO result_id;
  IF p_wrong_question_ids IS NOT NULL THEN
    FOREACH wq_id IN ARRAY p_wrong_question_ids LOOP
      INSERT INTO wrong_question (user_id, question_id, wrong_count, last_wrong_at) VALUES (current_user_id, wq_id, 1, NOW()) ON CONFLICT (user_id, question_id) DO UPDATE SET wrong_count = wrong_question.wrong_count + 1, last_wrong_at = NOW(), reviewed = FALSE;
    END LOOP;
  END IF;
  SELECT json_build_object('id', result_id, 'success', TRUE) INTO result;
  RETURN result;
END;
$function$
;


